"""Prove HOD's JSON and reproduce the shipped builder without writing source."""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    os.chdir(ROOT)
    # Dependency/import errors are failures, never a silent skipped map check.
    sys.path.insert(0, str(ROOT / '.agents/skills/roblox-map/scripts'))
    import emit
    import prove
    import spec

    for path in ('hike-or-die.project.json', 'games/hike-or-die/map/profile.json'):
        json.loads((ROOT / path).read_text())
    map_path = 'games/hike-or-die/map/hike-trail.json'
    model = spec.load(map_path)
    checks, reach = prove.run(model, res=4.0)
    report, worst = prove.report(model, checks, reach)
    print(report)
    if worst not in (prove.PASS, prove.INFO):
        return 1
    emit._apply_lift(model)
    generated = ('--!nocheck\n'
                 '-- Generated by roblox-map; dynamic Instance class typing is validated by map proof.\n'
                 + emit.to_lua(model, 'hike-trail', None))
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / 'TrailMapGenerated.luau'
        target.write_text(generated)
        subprocess.run(['stylua', '--config-path', str(ROOT / 'stylua.toml'), str(target)], check=True)
        shipped = ROOT / 'games/hike-or-die/src/server/World/TrailMapGenerated.luau'
        if target.read_bytes() != shipped.read_bytes():
            print('FAIL: HOD generated map differs from JSON/profile/emitter; regenerate and review it.')
            return 1
    print('PASS: HOD map proof and generated source reproducibility (not strict types or live navigation)')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
