def build() -> Node:
	hub = folder("Hub")
	plaza = hub.add(folder("Plaza"))
	paths = hub.add(folder("Paths"))
	zones = hub.add(folder("Zones"))
	lake = hub.add(folder("Lake"))
	boundary = hub.add(folder("Boundary"))
	pads = hub.add(folder("ModePads"))
	glyphs = hub.add(folder("GlyphSpawns"))

	ground = cylinder("Ground", 0, -1, 0, 2, 600, PALETTE["ground"], material="Concrete")
	hub.add(ground)

	# Plaza (TASK-0126): Concrete bands, an amber rim strip, the plinth, the spawn plate, tiles and seating.
	plaza.add(cylinder("Ring_Outer", 0, 0.1, 0, 0.2, PLAZA_R * 2, PALETTE["plaza_a"], material="Concrete"))
	plaza.add(cylinder("Ring_Middle", 0, 0.2, 0, 0.4, 90, PALETTE["plaza_b"], material="Concrete"))
	plaza.add(cylinder("Ring_Inner", 0, 0.3, 0, 0.6, 66, PALETTE["plaza_c"], material="Concrete"))
	# The rim strip: a Neon disc just below the outer band's top, so 0.6 stud of it shows past the edge (paths cover it).
	plaza.add(cylinder("Rim_Strip", 0, 0.09, 0, 0.18, PLAZA_R * 2 + 1.2, PALETTE["amber"], material="Neon", collide=False,
		query=False, cast_shadow=False))
	plaza.add(cylinder("Plinth", 0, 0.6, 0, 1.2, 12, PALETTE["slot"]))
	plaza.add(cylinder("Plinth_Trim", 0, 0.9, 0, 0.3, 12.4, PALETTE["violet"], material="Neon", collide=False, query=False,
		cast_shadow=False))
	plaza.add(cylinder("Plinth_Cap", 0, 1.5, 0, 0.6, 8, PALETTE["slot"]))
	plaza.add(cylinder("Plinth_CapTrim", 0, 1.45, 0, 0.2, 8.4, PALETTE["violet"], material="Neon", collide=False, query=False,
		cast_shadow=False))

	# Spawn: the SpawnLocation keeps its place and footprint; the SpawnHex plate (a prop) sits under it, top at y = 0.5.
	spawn = make_part("Spawn", (8, 0.4, 8), (0, 0.3, SPAWN_Z), IDENT, PALETTE["daily"], cls="SpawnLocation", transparency=1.0,
		cast_shadow=False)
	spawn.props += ['<bool name="Neutral">true</bool>', '<int name="Duration">0</int>']
	plaza.add(spawn)

	tiles = plaza.add(folder("TileSlots"))
	# Puzzle tiles, decorative only (no logic): a Concrete centre on a Neon base, so 0.4 stud of colour frames each tile.
	for radius, count, top, glow in ((48, 24, 0.2, "cyan"), (39, 18, 0.4, "violet"), (22, 12, 0.6, "amber")):
		for i in range(count):
			ang = 2 * math.pi * (i + 0.5) / count
			x, z = radius * math.cos(ang), radius * math.sin(ang)
			if math.hypot(x - 0, z - SPAWN_Z) < 7:
				continue
			rot = from_columns((math.cos(ang), 0, math.sin(ang)), (0, 1, 0), (-math.sin(ang), 0, math.cos(ang)))
			tiles.add(make_part(f"Inset_{radius}_{i:02d}", (4, 0.08, 4), (x, top + 0.04, z), rot, PALETTE[glow], material="Neon",
				collide=False, query=False, cast_shadow=False))
			t = make_part(f"Slot_{radius}_{i:02d}", (3.2, 0.12, 3.2), (x, top + 0.06, z), rot, PALETTE["slot"], material="Concrete",
				collide=False, query=False, cast_shadow=False)
			t.tags.append("TileSlot")
			tiles.add(t)

	seats = plaza.add(folder("Seating"))
	path_angles = [0, 45, 90, 135, 180, 270]
	for k in range(48):
		deg = k * 7.5
		if any(min(abs(deg - p), 360 - abs(deg - p)) <= 11 for p in path_angles):
			continue
		ang = math.radians(deg)
		fr = Frame((math.cos(ang), math.sin(ang)))
		seats.add(fr.block(f"Seat_{k:02d}", 53, 0, 0.85, (6.4, 1.3, 2.8), PALETTE["seat"], cast_shadow=False))

	# ---- paths and zones ----
	dirs = {
		"N": (0, -1),
		"E": (1, 0),
		"W": (-1, 0),
		"SW": (-0.7071067, 0.7071067),
		"SE": (0.7071067, 0.7071067),
	}

	def add_path(label, a0, a1, color=PALETTE["path"]):
		fr = Frame(dirs[label])
		paths.add(fr.block(f"Path_{label}", (a0 + a1) / 2, 0, PATH_TOP - 0.2, (PATH_W, 0.4, a1 - a0), color))
		return fr

	def pad(zone_fr, mode, a, b, y, color):
		p = zone_fr.block(f"Pad_{mode}", a, b, y + 0.25, (10, 0.5, 10), color)
		p.tags.append("ModePad")
		p.attrs["Mode"] = mode
		pads.add(p)
		wx, wz = zone_fr.world(a, b)
		PADS.append({"mode": mode, "x": wx, "y": y + 0.5, "z": wz})

	def glyph(fr, name, a, b, surface_y, rarity, origin_override=None):
		if origin_override is not None:
			wx, wz = origin_override
		else:
			wx, wz = fr.world(a, b)
		y = surface_y + 2.5
		part = make_part(f"Glyph_{name}", (0.6, 0.6, 0.6), (wx, y, wz), IDENT, PALETTE["glyph"], transparency=1.0,
			collide=False, query=False)
		att = Node("Attachment", "GlyphSpawn")
		att.props += ['<bool name="Visible">false</bool>', cframe((0, 0, 0), IDENT)]
		att.tags.append("GlyphSpawn")
		att.attrs["Rarity"] = rarity
		part.add(att)
		glyphs.add(part)
		GLYPHS.append({"name": name, "rarity": rarity, "x": wx, "y": y, "z": wz})

	# N: Observatory / Daily. Three terraces (+8, +18, +32) stepped by ramps; tower on the top one (layout plan).
	n_fr = Frame(dirs["N"])
	rf = Frame(dirs["N"])
	thick = 1.0
	N_RAMPS = ((PLAZA_R + 1, PATH_TOP, 74.0, 8.0), (80.0, 8.0, 98.0, 18.0), (104.0, 18.0, 122.0, 32.0))
	rise_top = 32.0

	def ramp(name, a0, y0, a1, y1):
		run = a1 - a0
		phi = math.atan2(y1 - y0, run)
		length = math.hypot(run, y1 - y0)
		mid_a, mid_y = (a0 + a1) / 2, (y0 + y1) / 2
		cx = rf.out[0] * mid_a + rf.out[0] * math.sin(phi) * thick / 2
		cz = rf.out[1] * mid_a + rf.out[1] * math.sin(phi) * thick / 2
		cy = mid_y - math.cos(phi) * thick / 2
		paths.add(make_part(name, (PATH_W, thick, length), (cx, cy, cz), rf.rot(phi), PALETTE["path"]))

	for i, r in enumerate(N_RAMPS):
		ramp("Path_N_Ramp" + str(i + 1), *r)
	for name, a, rad, top, color in (
		("Terrace_1", 118, 46, 8.0, PALETTE["tier"]),
		("Terrace_2", 122, 24, 18.0, PALETTE["ground"]),
		("Terrace_3", 140, 22, 32.0, PALETTE["daily"]),
	):
		tx, tz = n_fr.world(a, 0)
		zones.add(cylinder(name, tx, top / 2, tz, top, rad * 2, color, material="Concrete"))
	tx, tz = n_fr.world(150, 0)
	zones.add(cylinder("Observatory_Tower", tx, rise_top + 20, tz, 40, 16, PALETTE["daily"]))
	zones.add(make_part("Observatory_Dome", (22, 22, 22), (tx, rise_top + 46, tz), IDENT, PALETTE["daily"], shape="Ball"))
